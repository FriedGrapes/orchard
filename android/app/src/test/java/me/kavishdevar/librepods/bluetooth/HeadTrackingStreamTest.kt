    @Test fun AirPods_4는_16번() = assertEquals(0x10, HeadTrackingStream.motionStreamId(airPods4Motion))

    @Test fun AirPods_5는_15번() = assertEquals(0x0F, HeadTrackingStream.motionStreamId(airPods5Motion))

    @Test fun 머리_센서가_아닌_설명서는_무시() = assertNull(HeadTrackingStream.motionStreamId(airPods5HostHid))

    @Test fun 짧은_응답이나_엉뚱한_패킷은_무시() {
        assertNull(HeadTrackingStream.motionStreamId(hex("04 00 04 00 17 00 00 00 10 00 08 00 08 05 10 03 4A 02 08 10")))
        assertNull(HeadTrackingStream.motionStreamId(hex("04 00 04 00 04 00 03 04 01 55 02 01")))
    }

    @Test fun 번호를_넣은_시작_요청은_검증된_모양() {
        // 실기기(AirPods 5)에서 그래프가 움직인 요청과 같은 바이트
        assertArrayEquals(
            hex("17 00 00 00 10 00 0F 00 08 73 42 0B 08 0F 10 02 1A 05 01 40 9C 00 00"),
            HeadTrackingStream.startPacket(0x0F)
        )
        assertArrayEquals(
            hex("17 00 00 00 10 00 0F 00 08 75 42 0B 08 0F 10 02 1A 05 01 00 00 00 00"),
            HeadTrackingStream.stopPacket(0x0F)
        )
    }

    @Test fun 연결_때_통로_목록_신호에서_배운다() {
        assertEquals(0x0F, HeadTrackingStream.motionStreamId(hex("04 00 04 00 17 00 00 00 10 00 08 00 08 03 10 03 62 02 08 0F")))
        assertEquals(0x10, HeadTrackingStream.motionStreamId(hex("04 00 04 00 17 00 00 00 10 00 08 00 08 03 10 03 62 02 08 10")))
        // 번호가 둘 든 목록(일반 장치 통로들)은 머리 센서가 아니다
        assertNull(HeadTrackingStream.motionStreamId(hex("04 00 04 00 17 00 00 00 10 00 0C 00 08 04 10 03 62 02 08 0C 62 02 08 11")))
    }

